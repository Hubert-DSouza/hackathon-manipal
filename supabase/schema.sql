-- Ripple Supabase Schema (Updated with Anonymous Suggestions)

-- 1. Create profiles table
create table if not exists public.profiles (
  id uuid references auth.users on delete cascade primary key,
  full_name text,
  avatar_url text,
  ripple_points integer default 50,
  credibility_score numeric(4,1) default 94.0,
  updated_at timestamp with time zone default timezone('utc'::text, now())
);

-- RLS for profiles
alter table public.profiles enable row level security;
drop policy if exists "Allow public read profiles" on public.profiles;
create policy "Allow public read profiles" on public.profiles for select using (true);
drop policy if exists "Allow users update own profile" on public.profiles;
create policy "Allow users update own profile" on public.profiles for update using (auth.uid() = id);
drop policy if exists "Allow users insert own profile" on public.profiles;
create policy "Allow users insert own profile" on public.profiles for insert with check (auth.uid() = id);

-- 2. Create events table
create table if not exists public.events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  author_name text default 'Community Member',
  author_credibility numeric(4,1) default 94.0,
  title text not null,
  description text,
  category text default 'Roads',
  location text not null,
  latitude numeric(9,6) default 13.3521,
  longitude numeric(9,6) default 74.7947,
  distance numeric(4,1) default 0.4,
  seen integer default 1,
  confirmed integer default 0,
  likes_count integer default 0,
  comments_count integer default 0,
  impact_note text,
  image text,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Ensure missing columns exist on existing events table
alter table public.events add column if not exists description text;
alter table public.events add column if not exists impact_note text;

-- RLS for events
alter table public.events enable row level security;
drop policy if exists "Allow public read events" on public.events;
create policy "Allow public read events" on public.events for select using (true);
drop policy if exists "Allow public insert events" on public.events;
create policy "Allow public insert events" on public.events for insert with check (true);
drop policy if exists "Allow public update events" on public.events;
create policy "Allow public update events" on public.events for update using (true);

-- 3. Create suggestions table (Anonymous Community Notes)
create table if not exists public.suggestions (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete set null,
  content text not null,
  location text default 'Manipal',
  agree_count integer default 1,
  comments_count integer default 0,
  is_anonymous boolean default true,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- RLS for suggestions
alter table public.suggestions enable row level security;
drop policy if exists "Allow public read suggestions" on public.suggestions;
create policy "Allow public read suggestions" on public.suggestions for select using (true);
drop policy if exists "Allow public insert suggestions" on public.suggestions;
create policy "Allow public insert suggestions" on public.suggestions for insert with check (true);
drop policy if exists "Allow public update suggestions" on public.suggestions;
create policy "Allow public update suggestions" on public.suggestions for update using (true);
drop policy if exists "Allow delete own suggestions" on public.suggestions;
create policy "Allow delete own suggestions" on public.suggestions for delete using (auth.uid() = user_id or user_id is null);

